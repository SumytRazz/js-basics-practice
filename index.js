// ===== VARIABLES PRACTICE =====

// let example
let name = "Sumit";
let age = 20;

console.log("Name:", name);
console.log("Age:", age);

// changing value
age = 21;
console.log("Updated Age:", age);

// const example
const country = "Nepal";
console.log("Country:", country);

// var example (avoid in real projects)
var city = "Kathmandu";
console.log("City:", city);